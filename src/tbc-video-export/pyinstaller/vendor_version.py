"""Vendor version injection for the PyInstaller freezes.

The frozen tbc-video-export binary re-executes consts.py at runtime, where the
TBC_VIDEO_EXPORT_VENDOR_* environment variables (normally exported by the
CMake-generated wrapper) and any installed tbc-video-export distribution do
not exist, so consts falls back to the "0.0.0" placeholder. Capture the
build-time version into the artifact instead: a PyInstaller runtime hook (run
by the bootloader before the entry module imports) sets the vendor variables,
reusing consts' existing version[+commit] resolution chain.
"""

from __future__ import annotations

import os
import subprocess
from pathlib import Path

import dunamai

ENV_PREFIX = "TBC_VIDEO_EXPORT_VENDOR_"


def _git_version() -> str:
    """Return the dunamai base version from git, or "" when unavailable."""
    try:
        # current dunamai (1.22+) exposes Version.from_git(); the old module-level
        # from_git() was removed, so call the classmethod the build scripts use
        return dunamai.Version.from_git().base
    except Exception:  # not a git checkout, no matching tag, or git is unusable
        return ""


def _git_commit() -> str:
    """Return the short commit from git, or "" when unavailable."""
    try:
        result = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            check=True,
            capture_output=True,
            text=True,
        )
    except (OSError, subprocess.CalledProcessError):
        return ""
    return result.stdout.strip()


def resolve_vendor_version() -> tuple[str, str, str]:
    """Return the (version, commit, branch) to bake into this build.

    Resolution order (mirrors the CMake/Nix APP_VERSION/APP_COMMIT sources):
    1. TBC_VIDEO_EXPORT_VENDOR_{VERSION,COMMIT,BRANCH} environment set by CI
       (version read from vcpkg.json, commit from git rev-parse)
    2. git (dunamai tag version + short commit) for local builds
    3. "0.0.0" fallback with a loud warning (never a silent placeholder)
    """
    version = os.environ.get(f"{ENV_PREFIX}VERSION", "").strip()
    commit = os.environ.get(f"{ENV_PREFIX}COMMIT", "").strip()
    branch = os.environ.get(f"{ENV_PREFIX}BRANCH", "").strip()

    if not version:
        version = _git_version()
    if not commit:
        commit = _git_commit()

    if not version:
        print(
            f"WARNING: no vendor version available; set {ENV_PREFIX}VERSION or "
            "build from a git checkout. The frozen tbc-video-export will "
            'report "0.0.0".',
            flush=True,
        )
        version = "0.0.0"

    return version, commit, branch


def write_runtime_hook(build_dir: Path) -> tuple[Path, str]:
    """Write the vendor-version runtime hook; return (hook path, version)."""
    version, commit, branch = resolve_vendor_version()
    build_dir.mkdir(parents=True, exist_ok=True)
    hook_path = build_dir / "_vendor_runtime_hook.py"
    hook_path.write_text(
        "\n".join(
            [
                "# Generated by pyinstaller/vendor_version.py - do not edit.",
                "# PyInstaller runs this hook before the entry module: consts.py",
                "# resolves the vendor version from these environment variables.",
                "import os",
                "",
                f'os.environ.setdefault("{ENV_PREFIX}VERSION", "{version}")',
                f'os.environ.setdefault("{ENV_PREFIX}COMMIT", "{commit}")',
                f'os.environ.setdefault("{ENV_PREFIX}BRANCH", "{branch}")',
                "",
            ]
        ),
        encoding="utf-8",
    )
    print(
        f"Vendor version: {version} (commit: {commit or 'none'}, "
        f"branch: {branch or 'none'}) -> {hook_path}",
        flush=True,
    )
    return hook_path, version
